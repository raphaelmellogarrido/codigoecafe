// filtro em cascata (escolhe o distrito, depois a cidade dentro dele).
export const PORTUGAL_DISTRICTS = [...new Set(PORTUGAL_CITIES.map((c) => c.district))].sort((a, b) =>
  a.localeCompare(b, 'pt')
);

export function citiesInDistrict(district) {
  if (!district) return [];
  return PORTUGAL_CITIES.filter((c) => c.district === district);
}
